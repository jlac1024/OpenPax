#!/usr/bin/env python3
"""Catalog the GOG install: every file with size, sha256 and origin.

Usage:
  catalog.py <game folder> <output.toml>

Origin is one of:
  original      shipped with the 1997/98 game
  gog-replaced  an original file GOG overwrote with its own copy (goglog.ini
                records these as copied in from __support/)
  gog-added     wrappers, launcher, uninstaller, Galaxy files, ripped CD audio
  unreferenced  game-looking files the executable never names

Only reads the game folder. The output is ours, but it describes private
files, so it is written under build/.
"""

import configparser
import hashlib
import sys
from pathlib import Path, PureWindowsPath

GOG_ADDED_NAMES = {
    "goggame.sdb", "goglog.ini", "goggame-galaxyfilelist.ini", "gameuxinstallhelper.dll",
    "unins000.dat", "unins000.exe", "unins000.msg", "webcache.zip", "support.ico",
    "launch pax imperia - eminent domain.lnk",
    # CD audio replacement: winmm.dll proxies the system one and plays MUSIC/*.ogg
    # through libvorbisfile when the game asks MSS for redbook tracks.
    "winmm.dll", "libogg-0.dll", "libvorbis-0.dll", "libvorbisfile-3.dll",
}


def origin_of(rel: str, replaced: set[str]) -> str:
    low = rel.lower()
    name = low.rsplit("/", 1)[-1]
    if low in replaced:
        return "gog-replaced"
    if name in GOG_ADDED_NAMES or name.startswith("goggame-") or low.startswith("__support/"):
        return "gog-added"
    if low.startswith("music/"):
        return "gog-added"
    if low.startswith("_movies_avi/"):
        return "unreferenced"
    return "original"


def replaced_by_gog(game: Path) -> set[str]:
    log = game / "goglog.ini"
    if not log.exists():
        return set()
    cp = configparser.ConfigParser(interpolation=None)
    cp.read(log, encoding="latin-1")
    out = set()
    for section in cp.sections():
        for key, value in cp.items(section):
            if key.startswith("f") and key[1:].isdigit():
                parts = PureWindowsPath(value).parts
                # Paths are absolute install paths; keep what follows the game folder.
                for i, p in enumerate(parts):
                    if p.lower() == game.name.lower():
                        out.add("/".join(parts[i + 1:]).lower())
                        break
    return out


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(argv: list[str]) -> None:
    if len(argv) != 2:
        raise SystemExit(__doc__)
    game, out = Path(argv[0]), Path(argv[1])
    replaced = replaced_by_gog(game)
    files = sorted((p for p in game.rglob("*") if p.is_file()), key=lambda p: p.relative_to(game).as_posix().lower())
    lines = [f"# Catalog of {game.name}. Generated by tools/catalog.py.", ""]
    counts: dict[str, int] = {}
    for p in files:
        rel = p.relative_to(game).as_posix()
        origin = origin_of(rel, replaced)
        counts[origin] = counts.get(origin, 0) + 1
        lines += [
            "[[file]]",
            f"path = {toml_str(rel)}",
            f"size = {p.stat().st_size}",
            f"sha256 = {toml_str(sha256_of(p))}",
            f"origin = {toml_str(origin)}",
            "",
        ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"{len(files)} files: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main(sys.argv[1:])
