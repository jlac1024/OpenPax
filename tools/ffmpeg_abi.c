/* Prints the FFmpeg struct offsets and constants that OpenPax.Media's
 * bindings need, as C# source. Compiled against the headers of the pinned
 * FFmpeg build by tools/gen_ffmpeg_abi.sh, so the offsets always match the
 * libraries the game ships. Only fields the bindings read are listed. */
#include <errno.h>
#include <stddef.h>
#include <stdio.h>
#include <libavcodec/avcodec.h>
#include <libavformat/avformat.h>
#include <libavutil/avutil.h>
#include <libavutil/pixfmt.h>
#include <libavutil/samplefmt.h>

#define FIELD(name, type, member) printf("    public const int %s = %zu;\n", name, offsetof(type, member))
#define VALUE(name, expr) printf("    public const int %s = %d;\n", name, (int)(expr))

int main(void)
{
    printf("// <auto-generated>\n");
    printf("// Generated by tools/gen_ffmpeg_abi.sh from the FFmpeg %s headers.\n", av_version_info());
    printf("// </auto-generated>\n\n");
    printf("namespace OpenPax.Media.Video;\n\n");
    printf("/// <summary>Struct offsets and constants of the FFmpeg build the game ships.</summary>\n");
    printf("public static class FfmpegAbi\n{\n");
    printf("    public const string Version = \"%s\";\n", av_version_info());
    VALUE("AvutilMajor", LIBAVUTIL_VERSION_MAJOR);
    VALUE("AvcodecMajor", LIBAVCODEC_VERSION_MAJOR);
    VALUE("AvformatMajor", LIBAVFORMAT_VERSION_MAJOR);

    FIELD("FormatNbStreams", AVFormatContext, nb_streams);
    FIELD("FormatStreams", AVFormatContext, streams);
    FIELD("StreamCodecpar", AVStream, codecpar);
    FIELD("StreamTimeBase", AVStream, time_base);
    FIELD("ParCodecType", AVCodecParameters, codec_type);
    FIELD("ParWidth", AVCodecParameters, width);
    FIELD("ParHeight", AVCodecParameters, height);
    FIELD("ParSampleRate", AVCodecParameters, sample_rate);
    FIELD("ParChannels", AVCodecParameters, ch_layout.nb_channels);
    FIELD("FrameData", AVFrame, data);
    FIELD("FrameLinesize", AVFrame, linesize);
    FIELD("FrameWidth", AVFrame, width);
    FIELD("FrameHeight", AVFrame, height);
    FIELD("FrameNbSamples", AVFrame, nb_samples);
    FIELD("FrameFormat", AVFrame, format);
    FIELD("FramePts", AVFrame, pts);
    FIELD("FrameColorRange", AVFrame, color_range);
    FIELD("FrameColorspace", AVFrame, colorspace);
    FIELD("FrameChannels", AVFrame, ch_layout.nb_channels);
    FIELD("PacketStreamIndex", AVPacket, stream_index);

    VALUE("MediaVideo", AVMEDIA_TYPE_VIDEO);
    VALUE("MediaAudio", AVMEDIA_TYPE_AUDIO);
    VALUE("PixYuv420p", AV_PIX_FMT_YUV420P);
    VALUE("PixYuv444p", AV_PIX_FMT_YUV444P);
    VALUE("SampleFltp", AV_SAMPLE_FMT_FLTP);
    VALUE("SampleFlt", AV_SAMPLE_FMT_FLT);
    VALUE("SampleS16", AV_SAMPLE_FMT_S16);
    VALUE("RangeFull", AVCOL_RANGE_JPEG);
    VALUE("SpaceBt709", AVCOL_SPC_BT709);
    VALUE("ErrorEof", AVERROR_EOF);
    VALUE("ErrorAgain", AVERROR(EAGAIN));
    printf("}\n");
    return 0;
}
