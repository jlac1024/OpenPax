#!/usr/bin/env python3
"""Generate src/OpenPax.Data/Install/KnownFiles.g.cs from the catalog.

Usage:
  gen_known_files.py <build/catalog/gog-files.toml> <KnownFiles.g.cs>

Lists the files the import check requires, with size and sha256. Left out:
files the original rewrites while it is played (PrefData, SpecData, saves),
GOG's launcher, uninstaller and wrapper DLLs, the unused AVIs, and the
original DLLs, which the port never loads. The executable is kept because
it identifies the build.
"""

import sys
import tomllib

SKIP_EXACT = {"data/prefdata", "data/specdata"}
SKIP_ORIGINAL_DLLS = {"mss32.dll", "smackw32.dll", "cdrvdl32.dll", "cdrvhf32.dll"}


def wanted(f: dict) -> bool:
    low = f["path"].lower()
    if low in SKIP_EXACT or low.startswith("saved games/"):
        return False
    if f["origin"] == "gog-added":
        return low.startswith("music/")
    if f["origin"] == "unreferenced":
        return False
    return low not in SKIP_ORIGINAL_DLLS


def main(argv: list[str]) -> None:
    if len(argv) != 2:
        raise SystemExit(__doc__)
    with open(argv[0], "rb") as f:
        files = [x for x in tomllib.load(f)["file"] if wanted(x)]
    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen_known_files.py from the catalog of GOG build 2.0.0.12.",
        "// </auto-generated>",
        "",
        "namespace OpenPax.Data.Install;",
        "",
        "/// <summary>Files the import check requires, with their size and sha256.</summary>",
        "internal static class KnownFiles",
        "{",
        "    public static KnownFile[] All { get; } =",
        "    [",
    ]
    for f in files:
        path = f["path"].replace("\\", "/").replace('"', '\\"')
        lines.append(f'        new("{path}", {f["size"]}, "{f["sha256"]}"),')
    lines += ["    ];", "}", ""]
    with open(argv[1], "w", newline="\n") as out:
        out.write("\n".join(lines))
    print(f"{len(files)} files")


if __name__ == "__main__":
    main(sys.argv[1:])
